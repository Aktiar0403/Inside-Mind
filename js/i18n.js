let current = "en";
export function setLang(l) { if (STRINGS[l]) { current = l; try { localStorage.setItem("mi.lang", l); } catch {} } }
export function getLang() { return current; }
export function initLang() { try { const s = localStorage.getItem("mi.lang"); if (s && STRINGS[s]) current = s; } catch {} return current; }
export function t(key, vars = {}) {
  const parts = key.split(".");
  let v = STRINGS[current];
  for (const p of parts) v = v?.[p];
  if (v === undefined) { v = STRINGS.en; for (const p of parts) v = v?.[p]; }
  if (typeof v !== "string") return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
export function localized(obj) { return obj?.[current] || obj?.en || ""; }
